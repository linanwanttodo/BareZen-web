package com.barezen.site;

import com.barezen.content.StaticContent;
import com.barezen.http.jdk.JdkHttpServerAdapter;
import com.barezen.plugins.openapi.ApiDocument;
import com.barezen.plugins.openapi.ApiResponse;
import com.barezen.plugins.openapi.Operation;
import com.barezen.plugins.openapi.OperationMetadata;
import com.barezen.plugins.openapi.Parameter;
import com.barezen.plugins.openapi.Schema;
import com.barezen.web.Headers;
import com.barezen.web.HttpMethod;
import com.barezen.web.Response;
import com.barezen.web.Router;
import java.io.IOException;
import java.net.InetSocketAddress;
import java.net.URI;
import java.net.URISyntaxException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;

/**
 * This website, served by the framework it documents.
 *
 * <p>The point of the exercise is not to have a website: it is to be a consumer that the framework cannot help more than
 * any other project could be. The pages are files on disk served through {@code barezen-content}; the routes are
 * registered the way an application registers them; {@code /openapi.json} is generated by the OpenAPI plugin's declared
 * data; {@code /health} is a plain lambda behind the contract's Handler interface; and the whole thing runs on the JDK adapter with no container in the
 * picture. ADR-0016 kept a frontend out of scope until "a real consumer with named rules" arrived — this is that
 * consumer, and ADR-0052 records what it proved and what it did not.</p>
 *
 * <p><b>There is no build step, on purpose.</b> No template engine, no markdown converter, no bundler: the HTML is
 * written by hand in {@code src/main/resources/web}, Maven copies it to {@code target/classes/web}, and every file under
 * that tree has to be reachable through {@link #router(Path)} — a test enumerates the directory and asks for each route,
 * so an asset added without a route fails the build. That replaces the drift a generator would have introduced: a
 * generated page can disagree with its source silently, while a hand-written one and a route table that omits it fail
 * loudly.</p>
 *
 * <p><b>Run it</b> with {@code java -cp <classes> com.barezen.site.Site [port]}, defaulting to 8080. The port is an
 * argument, not a system property or an environment variable — the rule the framework holds its own modules to applies
 * to this one too (ADR-0013).</p>
 */
public final class Site {

  /** A JSON body, because the document model can describe only JSON or nothing ({@link #document()}). */
  private static final byte[] HEALTHY = "{\"status\":\"ok\"}".getBytes(StandardCharsets.UTF_8);

  /**
   * The pages, in nav order: the address a reader types, and the file behind it.
   *
   * <p>Ordered rather than a map, because a {@code HashMap} iteration would make the route table's printing and the
   * first-missing-page error message depend on hashing — the same reason {@code ALLOW} is emitted in HTTP's order in
   * both adapters (ADR-0023 §3) rather than in a hash bucket's.
   */
  private static final List<String[]> PAGES = List.of(
      new String[] {"/", "index.html"},
      new String[] {"/docs/quick-start", "docs/quick-start.html"},
      new String[] {"/docs/routing", "docs/routing.html"},
      new String[] {"/docs/plugins", "docs/plugins.html"},
      new String[] {"/docs/security-and-data", "docs/security-and-data.html"},
      new String[] {"/docs/reference", "docs/reference.html"});

  /**
   * The Chinese pages, in the same order and with the same one-file-per-route rule.
   *
   * <p>A parallel tree under {@code web/zh} rather than a query parameter or a cookie, because a language is part of
   * the address a reader shares: {@code /zh/docs/plugins} is linkable, cacheable and server-rendered with nothing
   * deciding it at request time. The switcher is two {@code hreflang} links (ADR-0053).
   */
  private static final List<String[]> ZH_PAGES = List.of(
      new String[] {"/zh/", "zh/index.html"},
      new String[] {"/zh/docs/quick-start", "zh/docs/quick-start.html"},
      new String[] {"/zh/docs/routing", "zh/docs/routing.html"},
      new String[] {"/zh/docs/plugins", "zh/docs/plugins.html"},
      new String[] {"/zh/docs/security-and-data", "zh/docs/security-and-data.html"},
      new String[] {"/zh/docs/reference", "zh/docs/reference.html"});

  private Site() {}

  /**
   * The route table for this site.
   *
   * <p>One handler per page, one handler per asset, one route each: {@code Router} has no wildcard pattern by decision
   * and {@code StaticContent} serves one existing regular file by construction (ADR-0019 §19, ADR-0051), so the asset
   * list is read from disk at assembly rather than inferred at request time from a path a client supplied.</p>
   *
   * @param web the directory holding {@code index.html}, {@code docs/}, {@code zh/} and {@code assets/}
   * @return the frozen table the adapter serves
   * @throws IOException if the asset directory cannot be listed
   * @throws IllegalArgumentException if {@code web} is not a directory, or a mapped page is missing from it
   */
  public static Router router(Path web) throws IOException {
    if (!Files.isDirectory(web)) {
      throw new IllegalArgumentException("no site directory at " + web + "; the pages live in "
          + "src/main/resources/web and reach the classpath with the rest of the module's resources");
    }
    Router.Builder builder = Router.builder();
    for (String[] page : concat(PAGES, ZH_PAGES)) {
      Path file = web.resolve(page[1]);
      if (!Files.isRegularFile(file)) {
        throw new IllegalArgumentException("the route " + page[0] + " is mapped to " + page[1]
            + ", which is not in " + web + ". A page removed from the tree without its route would answer 404 forever"
            + " and nobody would notice until a reader did");
      }
      builder.route(HttpMethod.GET, page[0], StaticContent.file(file));
    }
    for (Path asset : assets(web)) {
      // The URL is the file name, not the relativized path: the tree keeps every asset under web/assets, and a route
      // built from the relative path would come out as /assets/assets/site.css — which is exactly what the coverage
      // test in SiteTest caught on this module's first run (ADR-0052).
      builder.route(HttpMethod.GET, "/assets/" + asset.getFileName(), StaticContent.file(asset));
    }
    // "/zh/" is the address every switcher links to and every hreflang names; a reader who types "/zh" is one missing
    // separator from that address, and the segment-count rule means the two are different routes (ADR-0019 §3). A
    // redirect keeps one canonical address per page instead of serving the same file from two of them.
    builder.route(HttpMethod.GET, "/zh", (request, params) ->
        new Response(301, Headers.of("Location", "/zh/"), new byte[0]));
    builder.route(HttpMethod.GET, "/health", (request, params) ->
        new Response(200, Headers.of("Content-Type", "application/json"), HEALTHY));
    builder.route(HttpMethod.GET, "/openapi.json", document().handler());
    return builder.build();
  }

  /** Every file under {@code web/assets}, sorted so the route order does not depend on the filesystem's. */
  static List<Path> assets(Path web) throws IOException {
    Path directory = web.resolve("assets");
    if (!Files.isDirectory(directory)) {
      throw new IllegalArgumentException("no assets directory at " + directory
          + "; the stylesheet is referenced by every page, so a site without one is a misassembly");
    }
    try (Stream<Path> files = Files.list(directory)) {
      return files.filter(Files::isRegularFile).sorted().toList();
    }
  }

  /**
   * The declared document behind {@code /openapi.json} — and deliberately a partial one.
   *
   * <p>{@link ApiResponse} can say "this response has a JSON body of this schema" or "this response has no body", and
   * nothing in between, so the HTML pages this site exists to serve are not in the document: describing
   * {@code GET /docs/plugins} as {@code empty("200", ...)} would be a document that teaches a client to expect no bytes
   * where a browser expects a page. The routes are declared here once as routes and once as operations because
   * {@code Router} exposes no enumeration — the cost ADR-0047 names as the unfinished half of the plugin line, and this
   * page is the honest place to show it rather than stretch the model to hide it.</p>
   */
  public static ApiDocument document() {
    Schema status = Schema.object(List.of(new Schema.Property("status", Schema.string(), true)));

    Operation getStatus = Operation.builder(
            new OperationMetadata(HttpMethod.GET, "/health", "Liveness of this site", List.of("site")))
        .response(ApiResponse.json("200", "the status object", status))
        .build();
    Operation getDocument = Operation.builder(
            new OperationMetadata(HttpMethod.GET, "/openapi.json", "This document", List.of("site")))
        .response(ApiResponse.json("200", "the document", status))
        .build();

    return ApiDocument.builder()
        .info("BareZen website", "1.0")
        .server("http://127.0.0.1:8080")
        .schema("status", status)
        .operations(List.of(getStatus, getDocument))
        .build();
  }

  /** Where the pages are, resolved from this class's own location rather than a working directory. */
  public static Path webRoot() {
    URI location;
    try {
      location = Site.class.getProtectionDomain().getCodeSource().getLocation().toURI();
    } catch (URISyntaxException | RuntimeException unreadable) {
      throw new IllegalStateException("cannot locate the classes directory this site was loaded from: "
          + unreadable.getMessage(), unreadable);
    }
    Path classes = Path.of(location);
    Path web = classes.resolve("web");
    if (!Files.isDirectory(web)) {
      throw new IllegalStateException("no web directory at " + web + ". The site is run from the reactor's classes"
          + " directory, where Maven has copied src/main/resources/web; it is not packaged as a jar, and serving from"
          + " inside a jar would need a classpath variant of StaticContent that ADR-0051 defers by name");
    }
    return web;
  }

  /**
   * Serves the site until the process is interrupted.
   *
   * @param args optionally one argument, the port to bind; anything else is refused rather than ignored
   * @throws Exception if the port is already taken or the pages cannot be read
   */
  public static void main(String[] args) throws Exception {
    int port = args.length == 0 ? 8080 : parsePort(args[0]);
    Router routes = router(webRoot());
    JdkHttpServerAdapter server = new JdkHttpServerAdapter(new InetSocketAddress("127.0.0.1", port), routes);
    Runtime.getRuntime().addShutdownHook(new Thread(server::stop, "barezen-site-shutdown"));
    server.start();
    System.out.println("BareZen site on http://127.0.0.1:" + server.port().getAsInt() + "/ (ctrl-c to stop)");
    Thread.currentThread().join();
  }

  /** The two page tables in one list, English first so the route printing reads in nav order. */
  private static List<String[]> concat(List<String[]> first, List<String[]> second) {
    List<String[]> all = new java.util.ArrayList<>(first.size() + second.size());
    all.addAll(first);
    all.addAll(second);
    return List.copyOf(all);
  }

  private static int parsePort(String argument) {
    int port;
    try {
      port = Integer.parseInt(argument);
    } catch (NumberFormatException notANumber) {
      throw new IllegalArgumentException("the port must be a number; got \"" + argument + "\". It is an argument"
          + " rather than a system property because hidden configuration is what this framework refuses elsewhere"
          + " (ADR-0013)", notANumber);
    }
    if (port < 0 || port > 65535) {
      throw new IllegalArgumentException("the port must be 0-65535; got " + port + ". 0 asks the operating system for"
          + " a free one");
    }
    return port;
  }
}
