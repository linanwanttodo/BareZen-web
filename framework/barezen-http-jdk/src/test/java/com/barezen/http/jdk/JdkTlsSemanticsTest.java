package com.barezen.http.jdk;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import com.barezen.core.config.Configuration;
import com.barezen.core.error.ConfigurationException;
import com.barezen.web.Router;
import java.io.IOException;
import java.net.InetSocketAddress;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyStore;
import java.time.Duration;
import java.util.Map;
import javax.net.ssl.SSLContext;
import javax.net.ssl.TrustManagerFactory;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Nested;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * TLS on the JDK adapter, driven entirely by two configuration keys and measured with a real handshake.
 *
 * <p>The keystore is generated per test by the running JDK's own {@code keytool} rather than committed: a checked-in
 * keystore is a file that looks like a credential in the repository, and a password in a test resource is the thing the
 * secret audit is supposed to find. What is asserted instead is the whole chain — a client that trusts exactly this
 * certificate gets a 200, a client that trusts the system's CAs fails the handshake, and a plaintext request to the TLS
 * port gets nothing it can read.
 */
class JdkTlsSemanticsTest {

  private static final String PASSWORD = "test-keystore-password-not-a-secret";
  private static final String ALIAS = "barezen";

  /**
   * A PKCS12 keystore for {@code localhost} and {@code 127.0.0.1}, valid for a day, generated by the JDK running this
   * build so the store type is whatever {@link KeyStore#getDefaultType()} reads back.
   */
  private static Path keystore(Path directory) throws Exception {
    Path store = directory.resolve("barezen-test.p12");
    String keytool = Path.of(System.getProperty("java.home"), "bin", "keytool").toString();
    Process process = new ProcessBuilder(keytool, "-genkeypair", "-alias", ALIAS, "-keyalg", "RSA", "-keysize", "2048",
        "-validity", "1", "-storetype", "PKCS12", "-keystore", store.toString(), "-storepass", PASSWORD,
        "-dname", "CN=localhost", "-ext", "SAN=dns:localhost,ip:127.0.0.1")
        .redirectErrorStream(true)
        .start();
    String output = new String(process.getInputStream().readAllBytes());
    assertThat(process.waitFor()).as("keytool exited 0; output was: " + output).isZero();
    assertThat(store).exists();
    return store;
  }

  private static Configuration tlsConfiguration(Path keystore) {
    return Configuration.inMemory(Map.of(
        Tls.KEYSTORE_PATH.name(), keystore.toString(),
        Tls.KEYSTORE_PASSWORD.name(), PASSWORD));
  }

  /** A client that trusts exactly the certificate in this keystore, and nothing else. */
  private static HttpClient trusting(Path keystore) throws Exception {
    KeyStore store = KeyStore.getInstance(KeyStore.getDefaultType());
    try (java.io.InputStream input = Files.newInputStream(keystore)) {
      store.load(input, PASSWORD.toCharArray());
    }
    TrustManagerFactory trust = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
    trust.init(store);
    SSLContext context = SSLContext.getInstance("TLS");
    context.init(null, trust.getTrustManagers(), null);
    return HttpClient.newBuilder().sslContext(context).connectTimeout(Duration.ofSeconds(5)).build();
  }

  private static JdkHttpServerAdapter start(Router router, Configuration configuration) {
    JdkHttpServerAdapter adapter = new JdkHttpServerAdapter(
        new InetSocketAddress("127.0.0.1", 0), router, configuration);
    adapter.start();
    return adapter;
  }

  private static Router router() {
    return Router.builder()
        .route(com.barezen.web.HttpMethod.GET, "/health",
            (request, ignored) -> new com.barezen.web.Response(200, com.barezen.web.Headers.of("Content-Type",
                "text/plain"), "secure-ok".getBytes(java.nio.charset.StandardCharsets.UTF_8)))
        .build();
  }

  @Nested
  @DisplayName("a configured keystore")
  class Configured {

    @Test
    void theSameRouteAnswersOverTls(@TempDir Path directory) throws Exception {
      Path keystore = keystore(directory);
      JdkHttpServerAdapter adapter = start(router(), tlsConfiguration(keystore));
      try {
        HttpResponse<String> response = trusting(keystore).send(
            HttpRequest.newBuilder(URI.create("https://localhost:" + adapter.port().getAsInt() + "/health"))
                .GET().build(), HttpResponse.BodyHandlers.ofString());

        assertThat(response.statusCode()).isEqualTo(200);
        assertThat(response.body()).isEqualTo("secure-ok");
      } finally {
        adapter.stop();
      }
    }

    @Test
    void theServerIsAnHttpsServerCreatedThroughTheSameLifecycle(@TempDir Path directory) throws Exception {
      JdkHttpServerAdapter adapter = start(router(), tlsConfiguration(keystore(directory)));
      try {
        // port() and isRunning() answer exactly as they do for the plaintext server: ADR-0024's contract is about
        // owning a lifecycle, and TLS is a property of the socket, not of the ownership.
        assertThat(adapter.isRunning()).isTrue();
        assertThat(adapter.port()).isPresent();
      } finally {
        adapter.stop();
      }
    }

    @Test
    void aClientTrustingTheSystemCasIsRefused(@TempDir Path directory) throws Exception {
      Path keystore = keystore(directory);
      JdkHttpServerAdapter adapter = start(router(), tlsConfiguration(keystore));
      try {
        HttpClient systemTrust = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(5)).build();
        assertThatThrownBy(() -> systemTrust.send(
            HttpRequest.newBuilder(URI.create("https://localhost:" + adapter.port().getAsInt() + "/health"))
                .GET().build(), HttpResponse.BodyHandlers.ofString()))
            .isInstanceOf(IOException.class);
      } finally {
        adapter.stop();
      }
    }

    @Test
    void aPlaintextRequestToTheTlsPortGetsNoReadableAnswer(@TempDir Path directory) throws Exception {
      JdkHttpServerAdapter adapter = start(router(), tlsConfiguration(keystore(directory)));
      try {
        int port = adapter.port().getAsInt();
        int status;
        try {
          status = RawHttp.request(port, "GET", "/health", java.util.List.of(), null).status();
        } catch (IOException refused) {
          status = 0;
        }

        // The handshake is what fails, and it fails without producing a response: nothing about the route table is
        // reachable to a client that does not speak TLS.
        assertThat(status).isZero();
      } finally {
        adapter.stop();
      }
    }

    @Test
    void theStartupLogNamesTheKeystoreAndNeverThePassword(@TempDir Path directory) throws Exception {
      try (CapturedLogs logs = CapturedLogs.record(JdkHttpServerAdapter.class.getName(),
          ch.qos.logback.classic.Level.INFO)) {
        JdkHttpServerAdapter adapter = start(router(), tlsConfiguration(keystore(directory)));
        try {
          String all = logs.events().stream()
              .map(ch.qos.logback.classic.spi.ILoggingEvent::getFormattedMessage)
              .reduce("", (left, right) -> left + "\n" + right);

          // The file is a fact an operator can act on; the password is not, and ADR-0050 keeps it out of every
          // message this module can produce.
          assertThat(all).contains("HTTPS").contains("keystore");
          assertThat(all).doesNotContain(PASSWORD);
        } finally {
          adapter.stop();
        }
      }
    }

    @Test
    void aRoutingAnswerOverTlsIsTheContractsOwnBytes(@TempDir Path directory) throws Exception {
      Path keystore = keystore(directory);
      JdkHttpServerAdapter adapter = start(router(), tlsConfiguration(keystore));
      try {
        HttpResponse<String> response = trusting(keystore).send(
            HttpRequest.newBuilder(URI.create("https://localhost:" + adapter.port().getAsInt() + "/nothing"))
                .GET().build(), HttpResponse.BodyHandlers.ofString());

        // ADR-0023 §2's answer travels unchanged across the encrypted socket: a 404 that names no path.
        assertThat(response.statusCode()).isEqualTo(404);
        assertThat(response.body()).isEqualTo("Not Found");
      } finally {
        adapter.stop();
      }
    }
  }

  @Nested
  @DisplayName("no keystore configured")
  class Unconfigured {

    @Test
    void theAdapterStillServesPlaintext() throws Exception {
      JdkHttpServerAdapter adapter = start(router(),
          Configuration.inMemory(Map.of()));
      try {
        assertThat(RawHttp.request(adapter.port().getAsInt(), "GET", "/health", java.util.List.of(), null).status())
            .isEqualTo(200);
      } finally {
        adapter.stop();
      }
    }

    @Test
    void anExplicitBlankPathFailsConstructionInsteadOfSilentlyServingPlaintext() {
      Configuration blank = Configuration.inMemory(Map.of(Tls.KEYSTORE_PATH.name(), "  "));

      assertThatThrownBy(() -> Tls.from(blank))
          .isInstanceOf(ConfigurationException.class)
          .hasMessageContaining(Tls.KEYSTORE_PATH.name())
          .hasMessageContaining("blank");
    }
  }

  @Nested
  @DisplayName("a misassembled keystore")
  class Refusals {

    @Test
    void aKeystoreWithoutAPasswordFailsConstructionNamingBothKeys(@TempDir Path directory) throws Exception {
      Path keystore = keystore(directory);
      Configuration noPassword = Configuration.inMemory(Map.of(Tls.KEYSTORE_PATH.name(), keystore.toString()));

      assertThatThrownBy(() -> Tls.from(noPassword))
          .isInstanceOf(ConfigurationException.class)
          .hasMessageContaining(Tls.KEYSTORE_PATH.name())
          .hasMessageContaining(Tls.KEYSTORE_PASSWORD.name());
    }

    @Test
    void aWrongPasswordFailsConstructionAndDoesNotEchoTheSecret(@TempDir Path directory) throws Exception {
      Path keystore = keystore(directory);
      Configuration wrong = Configuration.inMemory(Map.of(
          Tls.KEYSTORE_PATH.name(), keystore.toString(),
          Tls.KEYSTORE_PASSWORD.name(), "definitely-not-it"));

      assertThatThrownBy(() -> Tls.from(wrong))
          .isInstanceOf(ConfigurationException.class)
          .hasMessageContaining(keystore.getFileName().toString())
          .hasMessageNotContaining("definitely-not-it");
    }

    @Test
    void aMissingFileFailsConstructionNamingThePath(@TempDir Path directory) {
      Configuration missing = tlsConfigurationEmptyPath(directory);

      assertThatThrownBy(() -> Tls.from(missing))
          .isInstanceOf(ConfigurationException.class)
          .hasMessageContaining("barezen.http.jdk.tls.keystorePath");
    }

    @Test
    void theFailureLandsAtConstructionBeforeAnyPortIsBound(@TempDir Path directory) throws Exception {
      Configuration wrong = Configuration.inMemory(Map.of(
          Tls.KEYSTORE_PATH.name(), keystore(directory).toString(),
          Tls.KEYSTORE_PASSWORD.name(), "wrong-again"));

      assertThatThrownBy(() -> new JdkHttpServerAdapter(new InetSocketAddress("127.0.0.1", 0), router(), wrong))
          .isInstanceOf(ConfigurationException.class);
      // ADR-0031's rule for the body limit applies to the TLS keys too: a bad value is a startup error, and no
      // ephemeral port was spent finding it out.
    }

    private Configuration tlsConfigurationEmptyPath(Path directory) {
      return Configuration.inMemory(Map.of(
          Tls.KEYSTORE_PATH.name(), directory.resolve("absent.p12").toString(),
          Tls.KEYSTORE_PASSWORD.name(), PASSWORD));
    }
  }

}
